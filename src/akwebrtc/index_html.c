/* Built-in player page served at "/". Kept as a C string so the binary
 * is self-contained (no web root on the camera's tiny flash). */
const char akwebrtc_index_html[] =
"<!doctype html>\n"
"<html lang=\"en\"><head><meta charset=\"utf-8\">\n"
"<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">\n"
"<title>Camera</title>\n"
"<style>\n"
":root{color-scheme:light dark}\n"
"body{margin:0;font:14px system-ui,sans-serif;background:#111;color:#ddd}\n"
"video{display:block;width:100%;max-height:90vh;background:#000}\n"
"#bar{display:flex;gap:12px;align-items:center;padding:8px 16px}\n"
"button{font:inherit;padding:4px 12px}\n"
"</style></head><body>\n"
"<video id=\"v\" autoplay playsinline muted controls></video>\n"
"<div id=\"bar\"><button id=\"b\">Reconnect</button>"
"<button id=\"m\">Unmute</button><span id=\"s\">starting</span></div>\n"
"<script>\n"
"const v=document.getElementById('v'),s=document.getElementById('s');\n"
"let pc=null,loc=null;\n"
"function status(t){s.textContent=t;}\n"
"async function stop(){\n"
"  if(pc){pc.close();pc=null;}\n"
"  if(loc){try{await fetch(loc,{method:'DELETE',keepalive:true});}catch(e){}loc=null;}\n"
"}\n"
"function gathered(p){\n"
"  /* libpeer does not do trickle ICE: send the answer with all candidates */\n"
"  if(p.iceGatheringState==='complete')return Promise.resolve();\n"
"  return new Promise(r=>{\n"
"    const t=setTimeout(r,3000);\n"
"    p.addEventListener('icegatheringstatechange',()=>{\n"
"      if(p.iceGatheringState==='complete'){clearTimeout(t);r();}});\n"
"  });\n"
"}\n"
"async function start(){\n"
"  await stop();\n"
"  status('requesting offer');\n"
"  try{\n"
"    const r=await fetch('/api/offer',{method:'POST'});\n"
"    if(!r.ok){status('camera busy: '+r.status);return;}\n"
"    loc=r.headers.get('Location');\n"
"    const offer=await r.text();\n"
"    pc=new RTCPeerConnection();\n"
"    const ms=new MediaStream();\n"
"    v.srcObject=ms;\n"
"    pc.ontrack=e=>{ms.addTrack(e.track);};\n"
"    pc.onconnectionstatechange=()=>status(pc.connectionState);\n"
"    await pc.setRemoteDescription({type:'offer',sdp:offer});\n"
"    await pc.setLocalDescription(await pc.createAnswer());\n"
"    await gathered(pc);\n"
"    const a=await fetch(loc,{method:'POST',headers:{'Content-Type':'application/sdp'},\n"
"      body:pc.localDescription.sdp});\n"
"    if(!a.ok)status('answer rejected: '+a.status);\n"
"  }catch(e){status('error: '+e);}\n"
"}\n"
"document.getElementById('b').onclick=start;\n"
"document.getElementById('m').onclick=()=>{v.muted=!v.muted;\n"
"  document.getElementById('m').textContent=v.muted?'Unmute':'Mute';};\n"
"addEventListener('pagehide',stop);\n"
"start();\n"
"</script></body></html>\n";
